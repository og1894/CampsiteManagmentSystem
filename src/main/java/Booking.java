public class Booking {

    /*
    Bookings for stays/vacations are made for specific camping areas, and bookings are automatically
    assigned a suitable available plot/pitch within the camping area. Bookings are made by specific guests.
     */

    /*
    Add a booking to a given camping area. Properties that should be stored are:
    booking dates (start and end), camping area identifier, guest identifier, and
    information regarding booming preferences e.g. type (bungalow, or empty pitch),
    number of guests, powered or not, min size, minimum bedrooms (if applicable), and budget (€).
    The system should search all plots/pitches in the specified camping area and identify one
    that is available and matches all criteria. The booking is then made/recorded for that specific
    plot/pitch. If no suitable plot/pitch can be identified then the user is informed of this.
     */

    /*
    Cancel a booking. This will remove the pending booking record
    from the appropriate plot/pitch of the appropriate campsite camping area
     */

    /*
    View all pending bookings in both (1) a given campsite (organised first by camping area
    and then by plot/pitch), and (2) the overall system (organised by campsite, camping area,
    and plot/pitch). Appropriate booking details (plot/pitch, guests, dates, etc.) and totals should be displayed.
     */
}
